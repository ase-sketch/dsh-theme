"""Local-only composer prototype checks. No DSH profile or real messages touched."""
import argparse
import json
import sys
sys.stdout.reconfigure(encoding="utf-8")
from pathlib import Path
from playwright.sync_api import sync_playwright

parser = argparse.ArgumentParser()
parser.add_argument('--chrome', default='C:/Program Files/Google/Chrome/Application/chrome.exe')
parser.add_argument('--output', default=str(Path(__file__).resolve().parent.parent / '.dsh-tmp' / 'composer-v3'))
args = parser.parse_args()
out = Path(args.output)
out.mkdir(parents=True, exist_ok=True)
checks = []
errors = []
external_requests = []

def check(name, ok, evidence):
    checks.append({'name': name, 'pass': bool(ok), 'evidence': evidence})
    print(('PASS ' if ok else 'FAIL ') + name + ' | ' + json.dumps(evidence, ensure_ascii=False))

def box(page, selector):
    return page.locator(selector).bounding_box()

def height(page):
    return box(page, '#composer')['height']

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=args.chrome, headless=True)
    context = browser.new_context(viewport={'width': 1120, 'height': 850}, reduced_motion='reduce')
    page = context.new_page()
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('console', lambda m: errors.append(m.text) if m.type == 'error' else None)
    page.on('request', lambda r: external_requests.append(r.url) if r.url.startswith(('http:', 'https:')) else None)
    page.goto(Path(__file__).with_name('composer-v3.html').as_uri(), wait_until='networkidle')
    page.locator('#message').wait_for()
    baseline = height(page)
    geometry = page.evaluate("""() => {
      const e=document.querySelector('#message'),s=getComputedStyle(e);
      return {height:e.clientHeight,line:parseFloat(s.lineHeight),padding:parseFloat(s.paddingTop)+parseFloat(s.paddingBottom),scroll:e.scrollHeight,background:s.backgroundImage};
    }""")
    check('three complete writing lines', abs((geometry['height']-geometry['padding'])/geometry['line']-3)<0.01, geometry)
    check('no ruled background', geometry['background']=='none', geometry['background'])
    check('filled send enabled', page.locator('#send').is_enabled(), page.locator('#send').get_attribute('aria-label'))
    check('draft makes whale look up', page.locator('#whale').get_attribute('data-state')=='idle-look', page.locator('#whale').get_attribute('data-state'))
    whale=box(page,'#whale');editor=box(page,'#message');card=box(page,'#composer')
    check('whale enlarged without layout scaling',whale['width']==96 and whale['height']==96,whale)
    check('sprite sheet geometry follows enlarged frame',page.locator('#whale').evaluate('(e)=>getComputedStyle(e).backgroundSize')=='768px 864px',page.locator('#whale').evaluate('(e)=>getComputedStyle(e).backgroundSize'))
    check('whale does not occupy writing or footer', whale['y']+whale['height']<=editor['y'] and whale['x']+whale['width']<=card['x']+card['width'], {'whale':whale,'editor':editor})
    page.locator('#message').focus()
    page.screenshot(path=str(out/'light.png'),full_page=True)
    page.locator('#preview-scene').screenshot(path=str(out/'light-detail.png'))
    cb=box(page,'#composer')
    page.screenshot(path=str(out/'composer-light.png'),clip={'x':cb['x']-12,'y':cb['y']-48,'width':cb['width']+24,'height':cb['height']+100})
    # Preserve the distinct runtime surfaces rather than replacing them with one generic menu.
    summary=page.locator('.caption').inner_text()
    check('all runtime summaries visible on desktop',all(s in summary for s in ['28','327','42','tok/s','77.4k','97%','162K / 384K','Codex']),summary)
    for trigger,panel,fields in [
        ('runtime','runtime-menu',['会话统计','模型用时','工具调用用时','TTFT','TPS','166分29秒']),
        ('token-usage','token-menu',['Token 用量','77,400,337','未缓存输入','缓存读取','输出','缓存命中']),
        ('context-usage','context-menu',['上下文已用 42%','162K / 384K','系统提示词','工具定义','对话消息']),
    ]:
        page.locator('#'+trigger).hover()
        page.locator('#'+panel).wait_for(state='visible')
        text=page.locator('#'+panel).inner_text()
        check(panel+' full information',all(s in text for s in fields),text)
        b=box(page,'#'+panel)
        check(panel+' fits viewport',b['x']>=0 and b['y']>=0 and b['x']+b['width']<=1120 and b['y']+b['height']<=850,b)
        check(panel+' does not resize composer',height(page)==baseline,height(page))
        page.screenshot(path=str(out/(panel+'.png')),full_page=True)
        page.keyboard.press('Escape')
        page.mouse.move(0,0)
    page.locator('#optimize').click()
    page.screenshot(path=str(out/'settings.png'),full_page=True)
    page.locator('#options').screenshot(path=str(out/'settings-panel.png'))
    page.keyboard.press('Escape')
    # A wrong tooltip location must be detected by the bounds check.
    page.locator('#runtime').click()
    page.locator('#runtime-menu').evaluate("(e)=>{e.dataset.savedLeft=e.style.left;e.style.left='1200px';}")
    mutated=box(page,'#runtime-menu')
    check('tooltip bounds guard detects bad anchor',mutated['x']+mutated['width']>1120,mutated)
    page.locator('#runtime-menu').evaluate('(e)=>{e.style.left=e.dataset.savedLeft;delete e.dataset.savedLeft;}')
    restored=box(page,'#runtime-menu')
    check('tooltip negative control restores anchor',restored['x']>=0 and restored['x']+restored['width']<=1120,restored)
    page.keyboard.press('Escape')
    page.locator('[data-preset="empty"]').click()
    check('empty send disabled', page.locator('#send').is_disabled(), page.locator('#message').input_value())
    check('empty whale idle',page.locator('#whale').get_attribute('data-state')=='idle',page.locator('#whale').get_attribute('data-state'))
    check('empty height stable',height(page)==baseline,{'baseline':baseline,'actual':height(page)})
    page.locator('[data-preset="long"]').click()
    long_data=page.locator('#message').evaluate('(e)=>({client:e.clientHeight,scroll:e.scrollHeight,value:e.value})')
    check('long text internally scrolls',long_data['scroll']>long_data['client'],{'client':long_data['client'],'scroll':long_data['scroll']})
    check('long height stable',height(page)==baseline,height(page))
    page.locator('[data-preset="attachment"]').click()
    check('two sample attachments',page.locator('.attachment').count()==2,page.locator('.attachment').count())
    check('attachment height stable',height(page)==baseline,height(page))
    page.get_by_role('button',name='移除 项目说明.md',exact=True).click()
    check('attachment removal works',page.locator('.attachment').count()==1,page.locator('.attachment').count())
    page.locator('#quota').click()
    page.locator('#refresh-quota').click()
    check('quota refresh works',page.locator('#quota').inner_text()=='Codex 可用 49%',page.locator('#quota').inner_text())
    check('quota height stable',height(page)==baseline,height(page))
    page.keyboard.press('Escape')
    page.locator('#model').click()
    page.locator('[data-model="flash"]').click()
    label=page.locator('#model-label').evaluate('(e)=>({text:e.textContent,scroll:e.scrollWidth,client:e.clientWidth})')
    check('full model label readable',label['text']=='DeepSeek-V4.1-Flash · High' and label['scroll']<=label['client'],label)
    page.locator('#optimize').click()
    dialog=box(page,'#options')
    check('options inside viewport',dialog['x']>=0 and dialog['y']>=0 and dialog['x']+dialog['width']<=1120 and dialog['y']+dialog['height']<=850,dialog)
    check('context disabled when optimization off',page.locator('#context-rounds').is_disabled(),page.locator('#context-rounds').is_disabled())
    check('full original settings represented',all(page.locator('#options').get_by_text(name,exact=True).count()>0 for name in ['档位','英文模式','协作基调','权限','模型','思考档位','上下文','实验性功能','推理增强']),page.locator('#options').inner_text())
    page.locator('#optimization-switch').click()
    check('optimization state sync',page.locator('#optimize-label').inner_text()=='标准 · 自动 · 工具开' and page.locator('#optimization-switch').get_attribute('aria-pressed')=='true',page.locator('#optimize-label').inner_text())
    check('context enabled with optimization',page.locator('#context-rounds').is_enabled(),page.locator('#context-rounds').is_enabled())
    page.locator('[data-english="on"]').click()
    page.locator('[data-tone="strict"]').click()
    page.locator('#optimizer-thinking').select_option('Medium')
    page.locator('#context-rounds').fill('9')
    page.locator('#bash-switch').click()
    options=page.evaluate('composerDemo.getState().options')
    check('complete option states are interactive',options['english'] and options['tone']=='strict' and options['thinking']=='Medium' and options['rounds']==9 and not options['bash'],options)
    page.locator('#show-option-details').click()
    check('optimization details expand',page.locator('#option-details').is_visible(),page.locator('#show-option-details').get_attribute('aria-expanded'))
    page.keyboard.press('Escape')
    check('escape restores options focus',page.locator('#optimize').evaluate('(e)=>document.activeElement===e'),page.evaluate('document.activeElement.id'))
    page.locator('#permission').click()
    page.locator('[data-permission="workspace"]').click()
    check('permission label updates locally',page.locator('#permission-label').inner_text()=='工作区内修改',page.locator('#permission-label').inner_text())
    page.locator('[data-preset="crowded"]').click()
    page.locator('#narrow').click()
    def row_geometry():
        return page.evaluate("""() => {
          const nodes=[...document.querySelectorAll('#tools button,#model,#send')].filter(e=>e.getBoundingClientRect().width>0);
          const centers=nodes.map(e=>{const r=e.getBoundingClientRect();return r.top+r.height/2;});
          const tools=document.querySelector('#tools');
          return {spread:Math.max(...centers)-Math.min(...centers),toolsClient:tools.clientWidth,toolsScroll:tools.scrollWidth,pageClient:document.documentElement.clientWidth,pageScroll:document.documentElement.scrollWidth};
        }""")
    row=row_geometry()
    check('crowded controls share one baseline',row['spread']<=1,row)
    check('crowded tools scroll instead of wrapping',row['toolsScroll']>row['toolsClient'],row)
    check('crowded height stable',height(page)==baseline,height(page))
    page.locator('#preview-scene').screenshot(path=str(out/'narrow.png'))
    for width in [900,640,420,360]:
        page.set_viewport_size({'width':width,'height':850})
        row=row_geometry();model=box(page,'#model');send=box(page,'#send');card=box(page,'#composer')
        check('no page overflow at '+str(width),row['pageScroll']<=row['pageClient'],row)
        check('single toolbar row at '+str(width),row['spread']<=1,row['spread'])
        check('model and send remain within card at '+str(width),model['x']>=card['x'] and send['x']+send['width']<=card['x']+card['width'],{'model':model,'send':send,'card':card})
        check('three writing lines at '+str(width),page.locator('#message').evaluate('(e)=>e.clientHeight')==76,page.locator('#message').evaluate('(e)=>e.clientHeight'))
        page.locator('#token-usage').click()
        popup=box(page,'#token-menu')
        check('token details inside width '+str(width),popup['x']>=0 and popup['x']+popup['width']<=width,popup)
        page.keyboard.press('Escape')
    page.set_viewport_size({'width':420,'height':500})
    page.locator('#optimize').click()
    compact=box(page,'#options')
    check('settings fit short narrow viewport',compact['x']>=0 and compact['y']>=0 and compact['x']+compact['width']<=420 and compact['y']+compact['height']<=500,compact)
    page.locator('#enhancement').scroll_into_view_if_needed()
    option=box(page,'#enhancement')
    check('last setting reachable inside scrolling panel',option['y']>=compact['y'] and option['y']+option['height']<=compact['y']+compact['height'],option)
    page.keyboard.press('Escape')
    page.set_viewport_size({'width':1120,'height':850})
    page.locator('#narrow').click()
    page.locator('[data-preset="daily"]').click()
    page.locator('#theme').click()
    check('independent dark tokens',page.locator('#composer').evaluate('(e)=>getComputedStyle(e).backgroundColor')=='rgb(20, 24, 36)',page.locator('#composer').evaluate('(e)=>getComputedStyle(e).backgroundColor'))
    page.locator('#message').focus()
    page.screenshot(path=str(out/'dark.png'),full_page=True)
    page.locator('#preview-scene').screenshot(path=str(out/'dark-detail.png'))
    cb=box(page,'#composer')
    page.screenshot(path=str(out/'composer-dark.png'),clip={'x':cb['x']-12,'y':cb['y']-48,'width':cb['width']+24,'height':cb['height']+100})
    page.locator('#message').fill('第一行')
    page.locator('#message').press('Shift+Enter')
    check('shift-enter inserts newline', '\n' in page.locator('#message').input_value(),repr(page.locator('#message').input_value()))
    page.locator('#message').evaluate("(e)=>e.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true,isComposing:true}))")
    check('IME enter does not send',page.evaluate('composerDemo.getState().phase')=='idle',page.evaluate('composerDemo.getState().phase'))
    page.locator('#message').press('Enter')
    check('enter starts sending',page.evaluate('composerDemo.getState().phase')=='sending',page.evaluate('composerDemo.getState().phase'))
    check('sending whale uses work state',page.locator('#whale').get_attribute('data-state')=='typing',page.locator('#whale').get_attribute('data-state'))
    check('sending height stable',height(page)==baseline,height(page))
    page.get_by_role('button',name='停止生成',exact=True).click()
    check('stop keeps draft',page.evaluate('composerDemo.getState().phase')=='idle' and '第一行' in page.locator('#message').input_value(),page.evaluate('composerDemo.getState()'))
    page.get_by_role('button',name='发送消息',exact=True).click()
    page.wait_for_function("composerDemo.getState().phase==='idle'",timeout=5000)
    check('completion clears editor and enables empty state',page.locator('#message').input_value()=='' and page.locator('#send').is_disabled(),page.locator('#message').input_value())
    check('completion height stable',height(page)==baseline,height(page))
    page.locator('#message').fill('已发送的任务')
    page.get_by_role('button',name='发送消息',exact=True).click()
    page.locator('#message').fill('正在写的下一条草稿')
    page.locator('#message').press('Enter')
    check('enter while generating does not cancel',page.evaluate('composerDemo.getState().phase')=='sending',page.evaluate('composerDemo.getState().phase'))
    page.wait_for_function("composerDemo.getState().phase==='idle'",timeout=5000)
    check('new draft survives previous completion',page.locator('#message').input_value()=='正在写的下一条草稿',page.locator('#message').input_value())
    # Negative controls mutate only the rendered prototype, then restore it.
    page.locator('#message').evaluate("(e)=>{e.dataset.oldStyle=e.getAttribute('style')||'';e.style.height='100px';e.style.minHeight='100px';e.style.maxHeight='100px';}")
    changed=height(page)
    check('height guard detects injected growth',changed!=baseline,{'baseline':baseline,'mutant':changed})
    page.locator('#message').evaluate("(e)=>{e.setAttribute('style',e.dataset.oldStyle);delete e.dataset.oldStyle;}")
    check('negative control restores height',height(page)==baseline,height(page))
    check('reduced motion removes transitions',page.locator('#send').evaluate('(e)=>getComputedStyle(e).transitionDuration')=='0s',page.locator('#send').evaluate('(e)=>getComputedStyle(e).transitionDuration'))
    check('no browser errors',len(errors)==0,errors)
    check('no external data transmission',len(external_requests)==0,external_requests)
    context.close()
    browser.close()

report={'passed':sum(c['pass'] for c in checks),'total':len(checks),'checks':checks}
(out/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print('RESULT: '+str(report['passed'])+'/'+str(report['total']))
raise SystemExit(0 if report['passed']==report['total'] else 1)
